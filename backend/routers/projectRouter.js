const express = require('express')
const {getProjects, addProject, deleteProject, updateProject, updateProjectStatus} = require('../controllers/projectController')
const {authMiddleware} = require('../middlewares/auth')
const adminMiddleware = require('../middlewares/admin')
const projectRouter = express.Router()
projectRouter.get('/:clientId', authMiddleware, getProjects)
projectRouter.post('/add-project', authMiddleware, adminMiddleware, addProject)
projectRouter.delete('/:projectId', authMiddleware, adminMiddleware, deleteProject)
projectRouter.post('/:projectId', authMiddleware, adminMiddleware, updateProject)
projectRouter.post('/:projectId/update-status', authMiddleware, updateProjectStatus)
module.exports = projectRouter